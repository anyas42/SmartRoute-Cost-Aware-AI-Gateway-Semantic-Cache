class MockLLMProvider(BaseLLMProvider):
    """
    Mock LLM provider for local development, automated testing, and offline benchmarking.
    
    IMPORTANT: This is a simulation engine designed for testing gateway routing,
    caching, and metrics without incurring API costs. All answers generated by this
    provider are synthetic and clearly marked with a simulation disclaimer.
    """
    def __init__(
        self,
        simulate_latency: bool = True,
        simulate_failure_rate: float = 0.0
    ):
        self.simulate_latency = simulate_latency
        self.simulate_failure_rate = simulate_failure_rate

    async def generate(
        self,
        prompt: str,
        model: str,
        temperature: float = 0.7,
        max_tokens: int = 512
    ) -> LLMResponse:
        start_time = time.time()

        # Simulate optional random network/rate-limit failures for resilience testing
        if self.simulate_failure_rate > 0.0 and random.random() < self.simulate_failure_rate:
            raise RuntimeError("Mock Provider Error: Simulated 503 Service Unavailable / Rate Limit Exceeded")

        # Simulate realistic latency: Small tier (~80-150ms), Large tier (~300-600ms)
        if self.simulate_latency:
            if model == settings.LARGE_MODEL_NAME:
                sleep_time = random.uniform(0.35, 0.65)
            else:
                sleep_time = random.uniform(0.08, 0.18)
            await asyncio.sleep(sleep_time)

        # Generate realistic answer based on query keywords
        lower = prompt.lower()
        matched_content = None
        for key, text in MOCK_KNOWLEDGE_BASE.items():
            if key in lower:
                matched_content = text
                break

        if not matched_content:
            # Fallback synthetic response explaining the model simulation
            matched_content = (
                f"Synthetic response to '{prompt[:60]}...'. In production with a live API key, "
                f"this request would be processed by {model}."
            )

        # Clear prefix indicating simulation
        answer = f"[Simulated Response via {model}]: {matched_content}"

        prompt_tokens = count_tokens(prompt)
        completion_tokens = count_tokens(answer)
        total_tokens = prompt_tokens + completion_tokens
        latency_ms = round((time.time() - start_time) * 1000.0, 2)
        cost = estimate_cost(prompt_tokens, completion_tokens, model)

        return LLMResponse(
            content=answer,
            model=model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=latency_ms,
            estimated_cost=cost,
            actual_cost=None,  # In mock mode, no actual billing occurred
            provider="mock",
            is_mock=True,
            fallback_used=False
        )
